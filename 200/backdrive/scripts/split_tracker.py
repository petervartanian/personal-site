#!/usr/bin/env python3
"""Write the complete Tracker snapshot as ordered, crawlable script resources.

Run directly to repackage an existing snapshot without fetching or changing its
records. The importer calls the same writer whenever the source is refreshed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
from typing import Any


MAX_SCRIPT_BYTES = 1_900_000  # Leave headroom below Google's 2 MB fetch limit.
NOTICE = "// Source licenses and attribution: imports/ATTRIBUTION.md\n"
INITIAL_PREFIX = NOTICE + "window.BACKDRIVE_TRACKER="
BATCH_PREFIX = NOTICE + "window.BACKDRIVE_TRACKER.cases.push(..."
BATCH_SUFFIX = ");\n"


def encode(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def read_snapshot(output: Path) -> dict[str, Any]:
    source = output.read_text(encoding="utf-8")
    if not source.startswith(INITIAL_PREFIX) or not source.endswith(";\n"):
        raise ValueError("Unrecognized Tracker snapshot format")
    payload = json.loads(source[len(INITIAL_PREFIX):-2])
    manifest_path = output.with_name("tracker-manifest.json")
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for entry in manifest.get("outputFiles", [])[1:]:
            source = (output.parent.parent / entry["url"]).read_text(encoding="utf-8")
            if not source.startswith(BATCH_PREFIX) or not source.endswith(BATCH_SUFFIX):
                raise ValueError("Unrecognized Tracker batch format")
            payload["cases"].extend(json.loads(source[len(BATCH_PREFIX):-len(BATCH_SUFFIX)]))
    if len(payload["cases"]) != payload["metadata"]["count"]:
        raise ValueError("Tracker record count does not match its metadata")
    return payload


def write_tracker_snapshot(payload: dict[str, Any], output: Path) -> None:
    initial = INITIAL_PREFIX + encode({**payload, "cases": []}) + ";\n"
    if len(initial.encode("utf-8")) >= MAX_SCRIPT_BYTES:
        raise ValueError("Tracker metadata exceeds the script size budget")
    files = [(output, initial, 0)]
    records: list[str] = []
    size = len((BATCH_PREFIX + "[]" + BATCH_SUFFIX).encode("utf-8"))

    def flush() -> None:
        if records:
            filename = output.with_name(f"{output.stem}-cases-{len(files):03}.js")
            files.append((filename, BATCH_PREFIX + "[" + ",".join(records) + "]" + BATCH_SUFFIX, len(records)))

    for record in payload["cases"]:
        encoded = encode(record)
        record_size = len(encoded.encode("utf-8"))
        base_size = len((BATCH_PREFIX + "[]" + BATCH_SUFFIX).encode("utf-8"))
        if base_size + record_size >= MAX_SCRIPT_BYTES:
            raise ValueError(f"Tracker record {record.get('id')} exceeds the script size budget")
        if size + record_size + bool(records) >= MAX_SCRIPT_BYTES:
            flush()
            records = []
            size = base_size
        size += record_size + bool(records)
        records.append(encoded)
    flush()

    entries = []
    for filename, text, count in files:
        data = text.encode("utf-8")
        entries.append({"url": filename.relative_to(output.parent.parent).as_posix(),
                        "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "recordCount": count})
    manifest = dict(payload["metadata"], outputSha256=entries[0]["sha256"],
                    outputBytes=entries[0]["bytes"], outputFiles=entries)

    # Static deferred scripts execute in document order before catalog.js.
    index = output.parent.parent / "index.html"
    updated_html = None
    if index.exists():
        html = index.read_text(encoding="utf-8")
        tags = "\n".join(f'  <script src="{item["url"]}?v={item["sha256"][:12]}" defer></script>' for item in entries)
        replacement = "  <!-- Tracker snapshot: generated by scripts/split_tracker.py -->\n" + tags + "\n  <!-- /Tracker snapshot -->"
        pattern = r"  <!-- Tracker snapshot:.*?<!-- /Tracker snapshot -->"
        if not re.search(pattern, html, flags=re.S):
            pattern = r'  <script\b[^>]*src="' + re.escape(entries[0]["url"]) + r'(?:\?[^\"]*)?"[^>]*></script>'
        updated_html, count = re.subn(pattern, lambda _: replacement, html, count=1, flags=re.S)
        if count != 1:
            raise ValueError("Cannot locate the Tracker script block in index.html")

    for filename, text, _ in files:
        atomic_write(filename, text)
    atomic_write(output.with_name("tracker-manifest.json"), json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    if updated_html is not None:
        atomic_write(index, updated_html)
    current = {filename for filename, _, _ in files}
    for stale in output.parent.glob(f"{output.stem}-cases-*.js"):
        if stale not in current:
            stale.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "imports" / "tracker.js")
    args = parser.parse_args()
    payload = read_snapshot(args.output)
    write_tracker_snapshot(payload, args.output)
    print(f"Repackaged {len(payload['cases'])} records without changing the source snapshot")


if __name__ == "__main__":
    main()
